def test_source_order_posts_once_then_cancellation_reconciles_owned_sales(source_fixture,request):
    f=source_fixture;provider=request.node.callspec.params['source_fixture'];assert catalog_post(f,catalog_preview(f)).status_code==200
    item=stage(f,fixture_order(provider));p=plan(f,item);assert p['eligible'],p
    with ThreadPoolExecutor(max_workers=2) as pool:rs=list(pool.map(lambda _:post(f,item,p),[1,2]))
    assert all(r.status_code==200 for r in rs),[r.text for r in rs]
    iid=rs[0].json()['invoice_id'];assert {r.json()['invoice_id'] for r in rs}=={iid}
    with psycopg2.connect(os.environ['AI_TEST_DATABASE_URL']) as c,c.cursor() as q:
        q.execute('SELECT invoice_number,total_amount,payment_status,customer_name FROM invoices WHERE tenant_id=%s',(f[1][0],));row=q.fetchone();assert row[0].startswith(('SH-' if provider=='shopify' else 'WC-')+f[3]) and row[1:]==(13,'PAID',None)
        q.execute('SELECT quantity,unit_price,total_price,rounding_adjustment FROM invoice_items WHERE tenant_id=%s',(f[1][0],));assert q.fetchone()==(3,Decimal('3.3333'),10,Decimal('.0001'))
        for table,count in [('transactions',1),('inventory',0),('keel_provider_order_posts',1)]:
            q.execute('SELECT count(*) FROM '+table+' WHERE tenant_id=%s',(f[1][0],));assert q.fetchone()==(count,)
    # A distinct legitimate manual sale is never coalesced or removed by a store update.
    with psycopg2.connect(os.environ['AI_TEST_DATABASE_URL']) as c,c.cursor() as q:q.execute("INSERT INTO transactions(tenant_id,product_id,quantity_sold,unit_price,total_price,original_currency,sale_source,transaction_date) SELECT %s,product_id,1,1,1,'JOD','POS',now() FROM invoice_items WHERE tenant_id=%s AND invoice_id=%s",(f[1][0],f[1][0],iid))
    item2=stage(f,fixture_order(provider,'2026-10-26T02:00:00Z',True));p2=plan(f,item2);assert p2['eligible'],p2
    second=post(f,item2,p2);assert second.status_code==200,second.text;assert second.json()['invoice_id']==iid and second.json()['sales']==0
    with psycopg2.connect(os.environ['AI_TEST_DATABASE_URL']) as c,c.cursor() as q:
        q.execute("SELECT count(*),min(sale_source) FROM transactions WHERE tenant_id=%s",(f[1][0],));assert q.fetchone()==(1,'POS')
        q.execute('SELECT count(*) FROM audit_logs WHERE tenant_id=%s AND action_type=%s',(f[1][0],'PROVIDER_ORDER_POSTED'));assert q.fetchone()==(2,)
    replay=post(f,item2,p2);assert replay.json()['replayed']
    assert replay.json()['canonical_write_performed'] is False
    f[0].headers['Authorization']='Bearer '+create_access_token(f[1][1],f[2][1],email_verified=True)[0]
    assert f[0].get('/onboarding/sources/'+f[3]+'/provider-records/'+item2['business_revision_id']+'/order-preview').status_code==404


