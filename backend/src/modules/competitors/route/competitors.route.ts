import { Router } from 'express';
import { authenticateUser,requireTenant } from '../../../middleware/validators/validateUser.js';
import { handleCompetitor } from '../controller/competitors.controller.js';
const router=Router({mergeParams:true});
router.use(authenticateUser,requireTenant);
router.get('/',handleCompetitor('list'));
router.post('/',handleCompetitor('create'));
router.post('/discovery',handleCompetitor('discover'));
router.get('/:competitorId',handleCompetitor('profile'));
router.get('/:competitorId/catalog',handleCompetitor('catalogProducts'));
router.get('/:competitorId/products/:productId/candidates',handleCompetitor('productCandidates'));
router.post('/:competitorId/product-links',handleCompetitor('linkProduct'));
router.post('/:competitorId/mappings/:mappingId/preview',handleCompetitor('previewProduct'));
router.patch('/:competitorId/candidates/:candidateId',handleCompetitor('rejectCandidate'));
router.patch('/:competitorId',handleCompetitor('update'));
router.patch('/:competitorId/tracking',handleCompetitor('track'));
router.post('/:competitorId/sources/:sourceId/collections/retry',handleCompetitor('retryCollection'));
router.post('/:competitorId/sources/:sourceId/review',handleCompetitor('reviewSource'));
router.post('/:competitorId/monitoring',handleCompetitor('schedule'));
router.post('/:competitorId/discovery/:eventId/cancel', handleCompetitor('cancelDiscovery'));
router.patch('/:competitorId/mappings/:mappingId',handleCompetitor('confirm'));
export default router;
