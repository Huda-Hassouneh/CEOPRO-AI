"""Generate a source-linked config index; never reads .env or runtime secrets."""
import ast
from collections import defaultdict
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "docs/reference/ENVIRONMENT_INVENTORY.md"


def inventory():
    rows = defaultdict(list)
    dynamic = []
    for path in sorted([*(ROOT / "backend/src").rglob("*.py"), *(ROOT / "backend/image_server").rglob("*.py")]):
        if "tests" in path.parts or path.name.startswith("test_"):
            continue
        tree = ast.parse(path.read_text(encoding="utf-8-sig"))
        relative = path.relative_to(ROOT).as_posix()
        for node in ast.walk(tree):
            key, default = None, "No explicit default; inspect validation branch"
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.args:
                f = node.func
                getenv = isinstance(f.value, ast.Name) and f.value.id == "os" and f.attr == "getenv"
                envget = isinstance(f.value, ast.Attribute) and isinstance(f.value.value, ast.Name) and f.value.value.id == "os" and f.value.attr == "environ" and f.attr == "get"
                if not (getenv or envget):
                    continue
                if isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                    key = node.args[0].value
                    if len(node.args) > 1:
                        default = ast.unparse(node.args[1])
                else:
                    dynamic.append(f"{relative}:{node.lineno}")
            elif isinstance(node, ast.Subscript) and isinstance(node.value, ast.Attribute) and isinstance(node.value.value, ast.Name) and node.value.value.id == "os" and node.value.attr == "environ":
                if isinstance(node.slice, ast.Constant) and isinstance(node.slice.value, str):
                    key = node.slice.value
                    default = "Required by direct lookup"
                else:
                    dynamic.append(f"{relative}:{node.lineno}")
            if key and re.fullmatch("[A-Z][A-Z0-9_]+", key):
                if re.search("SECRET|PASSWORD|TOKEN|API_KEY|MASTER_KEY|DSN|DATABASE_URL", key):
                    default = "Private; inspect required/default validation (values intentionally omitted)"
                rows[key].append((relative, node.lineno, default))
    for path in sorted((ROOT / "frontend/src").rglob("*")):
        if path.suffix not in (".js", ".jsx"):
            continue
        text = path.read_text(encoding="utf-8-sig")
        for match in re.finditer(r"import\.meta\.env\.([A-Z][A-Z0-9_]+)", text):
            rows[match[1]].append((path.relative_to(ROOT).as_posix(), text.count("\n", 0, match.start())+1, "Public Vite build-time setting; empty unless configured"))
    return rows, dynamic


def render():
    rows, dynamic = inventory()
    lines = [
        "# Source environment inventory", "",
        "Generated by tools/dev/environment_inventory.py from backend production Python and frontend source. No .env or runtime credential file is read.", "",
        "Use [the curated environment guide](../ENVIRONMENT_VARIABLES.md) for everyday setup and safety. "
        "This index navigates advanced provider, worker, model and scheduling settings. "
        "Each link identifies the owning implementation/validation branch; references may have different defaults.", "",
        f"Static settings: **{len(rows)}**. Dynamic lookups: **{len(set(dynamic))}**. Test/scripts-only flags are outside this production-source inventory.", "",
        "Restart the owning API/worker after backend changes. Vite settings require restart/rebuild. "
        "Absence uses the listed default; direct lookups require configuration. "
        "Missing provider credentials mean unavailable capability, never a substitute result. A source default is not an approved financial value.", "",
        "| Variable | Owning module / feature reference | Code default or requirement |",
        "|---|---|---|",
    ]
    for key, sites in sorted(rows.items()):
        refs = "; ".join(f"[{p.rsplit('/',1)[-1]}:{n}](../../{p}#L{n})" for p,n,_ in sites[:4])
        defaults = "; ".join(dict.fromkeys(d for _,_,d in sites)).replace("|", "\\|").replace("\n", " ")[:280]
        lines.append(f"| {key} | {refs} | {defaults} |")
    lines += ["", "## Dynamic lookups", "", "Names depend on provider/catalog selection. Inspect the implementation rather than inventing a universal setting.", ""]
    for value in sorted(set(dynamic)):
        path, number = value.rsplit(":", 1)
        lines.append(f"- [{value}](../../{path}#L{number})")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("Environment inventory is stale; regenerate with python tools/dev/environment_inventory.py")
            raise SystemExit(1)
        print("Environment inventory matches source.")
    else:
        TARGET.parent.mkdir(exist_ok=True)
        TARGET.write_text(text, encoding="utf-8")
        print("Wrote source-linked environment inventory.")
